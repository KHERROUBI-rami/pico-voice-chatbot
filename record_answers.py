"""
Record the spoken ANSWERS that are stored inside the Pico, and build audio_data.h.   (PC side)

Usage (run it inside ~/chatboot):
    python record_answers.py          record all 10 answers one by one
    python record_answers.py 4 7      record only answers 4 and 7 (the other .wav files are kept)

For each answer: it shows the text, you press Enter and read it, it plays your recording
back (trimmed, same loudness for every answer), and you keep it or record it again.
Recordings are saved in answers/vN.wav; audio_data.h is rebuilt at the end
(it needs all 10 recordings to exist).

Format (the same one pc_receiver.py expects): 16 kHz, mono, UNSIGNED 8-bit raw bytes.
Names in audio_data.h: audio_v1 ... audio_v10 and audio_v1_len ... audio_v10_len.
"""
import os
import sys
import time
import wave

import numpy as np
import sounddevice as sd

FS = 16000
MAX_S = 5.0                 # longest recording; keep answers under about 4 seconds
OUT_DIR = "answers"
HEADER = "audio_data.h"
GAIN = 1.0                  # microphone gain (raise it if you are told the recording is too quiet)

# id -> (group, text to read).  Edit the texts as you like.
# The Pico picks the group by the recognized sentence:
#   hello  = answers to "hello how are you"        (ids 1, 2, 3)
#   about  = answers to "tell me about yourself"   (ids 4, 5, 6)
#   name   = answers to "what is your name"        (ids 7, 8, 9, 10)
TEXTS = {
    1:  ("hello", "Hello! I am fine, thank you. How can I help you?"),
    2:  ("hello", "Hi there! I am doing great. What can I do for you?"),
    3:  ("hello", "Hello! Nice to hear from you."),
    4:  ("about", "I am a voice chatbot running on a Raspberry Pi Pico 2 W."),
    5:  ("about", "I live on a tiny microcontroller and I understand a few sentences."),
    6:  ("about", "I can control an LED, and I ask the internet when I do not know."),
    7:  ("name",  "My name is Pico Bot."),
    8:  ("name",  "They call me Pico Bot."),
    9:  ("name",  "I am Pico Bot, nice to meet you."),
    10: ("name",  "You can call me Pico Bot."),
}

def wav_path(i):
    return os.path.join(OUT_DIR, f"v{i}.wav")

def process(x):
    """float recording -> trimmed, normalized, unsigned 8-bit samples (or None if too quiet)."""
    x = np.clip(x * GAIN, -1.0, 1.0)
    peak = float(np.max(np.abs(x)))
    if peak < 0.02:
        return None
    thr = max(0.01, 0.05 * peak)
    idx = np.where(np.abs(x) > thr)[0]
    start = max(int(idx[0]) - int(0.05 * FS), 0)                 # keep 50 ms before the speech
    end = min(int(idx[-1]) + int(0.10 * FS), len(x))             # and 100 ms after it
    x = x[start:end] / peak * 0.9                                # same loudness for every answer
    fade = int(0.005 * FS)
    if len(x) > 2 * fade:
        x[:fade] *= np.linspace(0.0, 1.0, fade)
        x[-fade:] *= np.linspace(1.0, 0.0, fade)
    return np.clip(np.rint(x * 127) + 128, 0, 255).astype(np.uint8)

def save_wav(i, u8):
    os.makedirs(OUT_DIR, exist_ok=True)
    with wave.open(wav_path(i), "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(1)
        wf.setframerate(FS)
        wf.writeframes(u8.tobytes())

def read_wav(i):
    with wave.open(wav_path(i), "rb") as wf:
        return wf.readframes(wf.getnframes())

def record_one(i):
    group, text = TEXTS[i]
    print(f'\n=== Answer {i} (for "{group}") ===')
    print(f'    Read this: "{text}"')
    while True:
        cmd = input("    Enter = record, s = skip, q = quit > ").strip().lower()
        if cmd == "q":
            return "quit"
        if cmd == "s":
            return "skip"

        for n in (3, 2, 1):
            print(f"    {n}...")
            time.sleep(0.7)
        print("    SPEAK NOW")
        audio = sd.rec(int(MAX_S * FS), samplerate=FS, channels=1, dtype="float32")
        sd.wait()

        u8 = process(audio[:, 0])
        if u8 is None:
            print("    Too quiet. Speak louder or closer to the microphone, then try again.")
            continue

        secs = len(u8) / FS
        print(f"    Recorded {secs:.1f} s ({len(u8)} bytes). Playing it back...")
        if secs > 4.0:
            print("    (long answer: it takes longer to send and the microphone stays muted meanwhile)")
        sd.play((u8.astype(np.float32) - 128.0) / 128.0, FS)
        sd.wait()

        if input("    Enter = keep, r = record again > ").strip().lower() == "r":
            continue
        save_wav(i, u8)
        print(f"    Saved {wav_path(i)}")
        return "ok"

def build_header():
    missing = [i for i in sorted(TEXTS) if not os.path.exists(wav_path(i))]
    if missing:
        print(f"\nNot building {HEADER}: recordings missing for ids {missing}.")
        print("Record them first (python record_answers.py <ids>).")
        return
    total = 0
    with open(HEADER, "w") as f:
        f.write("// Generated by record_answers.py (unsigned 8-bit, 16 kHz, mono). Do not edit.\n")
        f.write("#pragma once\n\n")
        for i in sorted(TEXTS):
            data = read_wav(i)
            total += len(data)
            f.write(f"const unsigned char audio_v{i}[] = {{\n")
            for k in range(0, len(data), 16):
                f.write("  " + ", ".join(f"0x{b:02x}" for b in data[k:k + 16]) + ",\n")
            f.write("};\n")
            f.write(f"const unsigned int audio_v{i}_len = {len(data)};\n\n")
    print(f"\n{HEADER} written: 10 answers, {total} bytes in total (the Pico has 4 MB of flash).")
    print("Next: copy it into the project folder, then  make streaming  and flash the Pico.")

def main():
    ids = [int(a) for a in sys.argv[1:]] if len(sys.argv) > 1 else sorted(TEXTS)
    for i in ids:
        if i not in TEXTS:
            print(f"Unknown answer id {i} (valid: 1..10)")
            return
    for i in ids:
        if record_one(i) == "quit":
            print("Stopped. Run the script again to continue.")
            break
    build_header()

if __name__ == "__main__":
    main()
